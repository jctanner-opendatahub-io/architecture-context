def test_missing_and_invalid_sidecars_preserve_seeded_safety_accounting(
    tmp_path: Path,
) -> None:
    inventory = _metrics_inventory()
    final = _write_document(tmp_path, "final.md", auth_row=False)

    missing = validate_surface_coverage(
        inventory=inventory,
        sidecar=None,
        promoted_document=final,
    )
    invalid_sidecar = copy.deepcopy(inventory)
    invalid_sidecar["surfaces"][0]["priority"] = "optional"
    invalid = validate_surface_coverage(
        inventory=inventory,
        sidecar=invalid_sidecar,
        promoted_document=final,
    )

    for report in (missing, invalid):
        assert report["structural_valid"] is False
        assert report["summary"] == {
            "seeded": 1,
            "documented": 0,
            "unresolved": 1,
            "not_applicable": 0,
        }
        assert report["unresolved_safety_critical_surfaces"] == [
            "authentication.metrics-enforcement"
        ]
        assert report["accounted_surfaces"][0] == inventory["surfaces"][0]
        assert any(
            item["surface_id"] == "authentication.metrics-enforcement"
            for item in report["validator_findings"]
        )
    recovered = finalized_sidecar(None, missing, inventory=inventory)
    assert recovered["surfaces"] == inventory["surfaces"]
    assert recovered["summary"]["unresolved"] == 1


