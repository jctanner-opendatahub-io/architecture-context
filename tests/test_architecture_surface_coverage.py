def _document(
    auth_row: bool, *, auth_mechanism: str = "controller-runtime filter"
) -> str:
    row = ""
    if auth_row:
        row = (
            f"| Operator metrics | HTTPS | {auth_mechanism} | "
            "metrics server | Conditional on secure serving |\n"
        )
    return f"""# Component: example

## Security

### Authentication & Authorization

| Endpoint | Methods | Auth Mechanism | Enforcement Point | Policy |
|----------|---------|----------------|-------------------|--------|
{row}
## Architectural Analysis

The component uses conditional metrics authentication when secure serving is enabled.
"""


