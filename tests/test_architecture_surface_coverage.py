def test_validator_distinguishes_unavailable_omitted_and_explicit_unresolved(
    tmp_path: Path,
) -> None:
    inventory = _metrics_inventory()
    final = _write_document(tmp_path, "final.md", auth_row=False)

    unavailable = copy.deepcopy(inventory)
    unavailable["surfaces"][0]["evidence_status"] = "unavailable"
    unavailable_report = validate_surface_coverage(
        inventory=inventory,
        sidecar=unavailable,
        promoted_document=final,
    )
    assert [
        item["classification"]
        for item in unavailable_report["validator_findings"]
    ] == ["extraction_gap"]

    omitted = copy.deepcopy(inventory)
    omitted["surfaces"][0]["evidence_status"] = "available"
    omitted["surfaces"][0]["evidence"] = [
        {"kind": "source-read", "reference": "cmd/main.go:480-500"}
    ]
    omitted_report = validate_surface_coverage(
        inventory=inventory,
        sidecar=omitted,
        promoted_document=final,
    )
    assert [
        item["classification"]
        for item in omitted_report["validator_findings"]
    ] == ["synthesis_omission"]

    explicit = copy.deepcopy(inventory)
    uninspected_report = validate_surface_coverage(
        inventory=inventory,
        sidecar=explicit,
        promoted_document=final,
    )
    assert [
        item["classification"]
        for item in uninspected_report["validator_findings"]
    ] == ["inspection_gap"]

    explicit_report = validate_surface_coverage(
        inventory=inventory,
        sidecar=explicit,
        promoted_document=final,
        observed_reads=[
            {
                "path": "config/metrics-service.yaml",
                "line_range": "1-20",
                "outcome": "partially-resolved",
            }
        ],
    )
    assert explicit_report["validator_findings"] == []
    assert explicit_report["summary"]["unresolved"] == 1
    assert explicit_report["unresolved_safety_critical_surfaces"] == [
        "authentication.metrics-enforcement"
    ]


