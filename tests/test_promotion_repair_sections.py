"""Regression coverage for synthesis subsection ownership during promotion.

These fixtures intentionally mirror the shape of the retained Claude canary
candidate: the candidate contains the required H2 sections and may add H3
material beneath one of them.  The section assembler owns the decision about
whether that H3 is allowed to enter the promoted document.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from lib.arch_doc import assemble_architecture_sections  # noqa: E402
from lib.architecture_merge import merge_architecture_files  # noqa: E402
from lib.phases import architecture as architecture_phase  # noqa: E402


def architecture_document(*, security: str = "", admission: str = "") -> str:
    """Return the smallest valid arch-doc input with optional H3 fixtures."""

    return f"""# Component: Example

## Metadata

- **Generated By**: arch-analyzer

## Purpose

Purpose text.

## Architectural Analysis

Analysis text.

## Architecture Components

Analyzer-owned component facts.

## APIs Exposed

Analyzer-owned API facts.

## Dependencies

Analyzer-owned dependency facts.

## Network Architecture

Analyzer-owned network facts.

## Security

{security}

## Admission Webhooks

{admission}

## Data Flows

Flow text.

## Integration Points

Analyzer-owned integration facts.

## Recent Changes

Recent changes.
"""


def with_candidate_security(candidate: str, security: str) -> str:
    return candidate.replace("## Security\n\n", f"## Security\n\n{security}\n")


@pytest.mark.parametrize(
    ("subsection", "body"),
    [
        (
            "FIPS Compliance",
            "Build evidence remains conditional on the recorded image and flags.",
        ),
        (
            "Build Hermeticity",
            "The build inputs are documented with their source references.",
        ),
    ],
)
def test_configured_synthesis_subsections_are_accepted_under_their_parent(
    subsection: str, body: str
) -> None:
    base = architecture_document()
    candidate = architecture_document(
        security=f"### {subsection}\n\n{body}\n"
    )

    assembled = assemble_architecture_sections(base, candidate)

    assert f"### {subsection}\n\n{body}" in assembled
    assert assembled.index("## Security") < assembled.index(
        f"### {subsection}"
    ) < assembled.index("## Data Flows")


@pytest.mark.parametrize("subsection", ["FIPS Compliance", "Build Hermeticity"])
def test_configured_subsection_under_admission_webhooks_is_rejected(
    subsection: str,
) -> None:
    base = architecture_document()
    candidate = architecture_document(
        admission=f"### {subsection}\n\nCandidate claim.\n"
    )

    with pytest.raises(ValueError, match=subsection):
        assemble_architecture_sections(base, candidate)


def test_misplaced_subsection_is_never_relocated_into_security() -> None:
    base = architecture_document()
    candidate = architecture_document(
        admission="### FIPS Compliance\n\nCandidate claim.\n"
    )

    with pytest.raises(ValueError, match="Admission Webhooks"):
        assemble_architecture_sections(base, candidate)


def test_analyzer_owned_and_unconfigured_h3_content_is_not_overwritten() -> None:
    base = architecture_document(
        security=(
            "### RBAC - Cluster Roles\n\nAnalyzer role facts.\n"
            "### FIPS Compliance\n\nAnalyzer FIPS facts.\n"
        )
    )
    candidate = architecture_document(
        security=(
            "### RBAC - Cluster Roles\n\nCandidate replacement.\n"
            "### FIPS Compliance\n\nCandidate FIPS facts.\n"
            "### Invented Security Detail\n\nCandidate unconfigured detail.\n"
        )
    )

    assembled = assemble_architecture_sections(base, candidate)

    assert "Analyzer role facts." in assembled
    assert "Candidate replacement." not in assembled
    assert "Candidate FIPS facts." not in assembled
    assert "Candidate unconfigured detail." not in assembled


def test_misplaced_section_failure_is_recorded_in_machine_readable_merge_report(
    tmp_path: Path,
) -> None:
    base_path = tmp_path / "base.md"
    candidate_path = tmp_path / "candidate.md"
    output_path = tmp_path / "merged.md"
    report_path = tmp_path / "merge.json"
    base_path.write_text(architecture_document())
    candidate_path.write_text(
        architecture_document(
            admission="### FIPS Compliance\n\nCandidate claim.\n"
        )
    )

    with pytest.raises(ValueError, match="FIPS Compliance"):
        merge_architecture_files(
            base_path,
            candidate_path,
            output_path,
            report_json=report_path,
            section_assembler=assemble_architecture_sections,
        )

    assert not output_path.exists()
    assert report_path.exists()
    report = json.loads(report_path.read_text())
    diagnostics = json.dumps(report.get("assembly_diagnostics", report))
    assert "FIPS Compliance" in diagnostics
    assert "Admission Webhooks" in diagnostics


def test_runner_propagates_misplaced_section_diagnostics(
    tmp_path: Path,
) -> None:
    checkout = tmp_path / "checkout"
    analyzer_root = tmp_path / "analyzer"
    log_dir = tmp_path / "logs"
    checkout.mkdir()
    analyzer_root.mkdir()
    log_dir.mkdir()
    analyzer = analyzer_root / "analyzer_architecture.md"
    candidate = tmp_path / "candidate.md"
    merged = tmp_path / "merged.md"
    final = tmp_path / "final.md"
    analyzer.write_text(architecture_document())
    candidate.write_text(
        architecture_document(
            admission="### FIPS Compliance\n\nCandidate claim.\n"
        )
    )
    result = {"success": True}
    job = {
        "name": "example",
        "checkout_path": checkout,
        "analyzer_root": analyzer_root,
        "candidate_path": candidate,
        "output_path": candidate,
        "merged_path": merged,
        "final_output_path": final,
        "insight_path": tmp_path / "unused-insights.json",
        "agent_policy": {"route": "partial", "gap_categories": []},
    }

    architecture_phase._merge_agent_outputs(
        [job], [result], log_dir, platform="rhoai", version="rhoai.next"
    )
    architecture_phase._write_agent_run_reports([job], [result], log_dir)

    assert result["success"] is False
    assert not final.exists()
    assert result["merge"]["assembly_status"] == "failed"
    diagnostics = result["merge"]["assembly_diagnostics"]
    assert diagnostics[0]["code"] == "synthesis_subsection_parent_mismatch"
    assert diagnostics[0]["actual_parent"] == "Admission Webhooks"
    assert Path(result["merge"]["report_json"]).is_file()
    durable = json.loads((log_dir / "example.run.json").read_text())
    assert durable["merge"]["assembly_diagnostics"] == diagnostics
